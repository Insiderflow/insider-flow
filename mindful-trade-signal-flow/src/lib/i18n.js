/** GICS sector labels in English (canonical for UI when locale is en). */
const GICS_EN_CANONICAL = [
  'Information Technology',
  'Financials',
  'Industrials',
  'Health Care',
  'Consumer Discretionary',
  'Communication Services',
  'Consumer Staples',
  'Energy',
  'Materials',
  'Real Estate',
  'Utilities',
];

const SECTOR_ZH_TO_EN = (() => {
  const m = Object.create(null);
  for (const lang of ['zh-Hant', 'zh-Hans']) {
    const map = SECTOR_DISPLAY[lang] || {};
    for (const [en, zh] of Object.entries(map)) {
      m[zh] = en;
    }
  }
  return m;
})();

/**
 * Map API/DB values (Chinese, compact GICS, or English variants) to canonical English GICS labels.
 */
export function toEnglishSectorLabel(sectorName) {
  if (sectorName == null || sectorName === '') return sectorName;
  const s = String(sectorName).trim();
  if (SECTOR_ZH_TO_EN[s]) return SECTOR_ZH_TO_EN[s];
  const compact = s.replace(/\s+/g, '').toLowerCase();
  const hit = GICS_EN_CANONICAL.find(
    (label) => label.replace(/\s+/g, '').toLowerCase() === compact,
  );
  if (hit) return hit;
  return s;
}

export function t(key, language = 'en') {
  return TRANSLATIONS[language]?.[key] ?? TRANSLATIONS.en[key] ?? key;
}

export function displaySector(sectorName, language) {
  if (!sectorName) return sectorName;
  const englishLabel = toEnglishSectorLabel(sectorName);
  if (language === 'en') return englishLabel;

  const localeMap = SECTOR_DISPLAY[language] || {};
  if (localeMap[englishLabel]) return localeMap[englishLabel];
  if (localeMap[sectorName]) return localeMap[sectorName];

  // Handle compact/raw variants like "InformationTechnology" or "ConsumerDiscretionary"
  const normalizedInput = String(sectorName).replace(/\s+/g, '').toLowerCase();
  const matchedKey = Object.keys(localeMap).find(
    (k) => k.replace(/\s+/g, '').toLowerCase() === normalizedInput,
  );
  if (matchedKey) return localeMap[matchedKey];
  // API sent an unknown string: show English canonical if we have it, else raw
  return englishLabel;
}

